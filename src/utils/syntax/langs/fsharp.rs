//! FSharp lexer traits and word tables.

use super::spec::LangSpec;

pub(super) const SPEC: LangSpec = LangSpec::new(b"//")
    .with_fsharp_block_comments()
    .keywords(is_keyword)
    .type_names(is_type_name)
    .builtins(is_builtin)
    .constants(is_constant);

pub(super) fn is_keyword(word: &str) -> bool {
    matches!(
        word,
        "abstract"
            | "and"
            | "as"
            | "assert"
            | "base"
            | "begin"
            | "class"
            | "default"
            | "delegate"
            | "do"
            | "done"
            | "downcast"
            | "downto"
            | "elif"
            | "else"
            | "end"
            | "exception"
            | "extern"
            | "false"
            | "finally"
            | "fixed"
            | "for"
            | "fun"
            | "function"
            | "global"
            | "if"
            | "in"
            | "inherit"
            | "inline"
            | "interface"
            | "internal"
            | "lazy"
            | "let"
            | "match"
            | "member"
            | "module"
            | "mutable"
            | "namespace"
            | "new"
            | "not"
            | "null"
            | "of"
            | "open"
            | "or"
            | "override"
            | "private"
            | "public"
            | "rec"
            | "return"
            | "sig"
            | "static"
            | "struct"
            | "then"
            | "to"
            | "true"
            | "try"
            | "type"
            | "upcast"
            | "use"
            | "val"
            | "void"
            | "when"
            | "while"
            | "with"
            | "yield"
    )
}

pub(super) fn is_type_name(word: &str) -> bool {
    matches!(
        word,
        "int"
            | "int8"
            | "int16"
            | "int32"
            | "int64"
            | "uint8"
            | "uint16"
            | "uint32"
            | "uint64"
            | "sbyte"
            | "byte"
            | "nativeint"
            | "unativeint"
            | "float"
            | "float32"
            | "single"
            | "double"
            | "decimal"
            | "bigint"
            | "bool"
            | "char"
            | "string"
            | "unit"
            | "list"
            | "array"
            | "seq"
            | "option"
            | "voption"
            | "Result"
            | "Map"
            | "Set"
            | "ResizeArray"
            | "Async"
            | "Task"
            | "Lazy"
            | "ref"
    )
}

