//! Php lexer traits and word tables.

use super::spec::LangSpec;

pub(super) const SPEC: LangSpec = LangSpec::new(b"//")
    .keywords(is_keyword)
    .builtins(is_builtin);

pub(super) fn is_keyword(word: &str) -> bool {
    matches!(
        word,
        "abstract"
            | "and"
            | "array"
            | "as"
            | "break"
            | "callable"
            | "case"
            | "catch"
            | "class"
            | "clone"
            | "const"
            | "continue"
            | "declare"
            | "default"
            | "die"
            | "do"
            | "echo"
            | "else"
            | "elseif"
            | "empty"
            | "enddeclare"
            | "endfor"
            | "endforeach"
            | "endif"
            | "endswitch"
            | "endwhile"
            | "eval"
            | "exit"
            | "extends"
            | "false"
            | "final"
            | "finally"
            | "fn"
            | "for"
            | "foreach"
            | "function"
            | "global"
            | "goto"
            | "if"
            | "implements"
            | "include"
            | "instanceof"
            | "interface"
            | "isset"
            | "list"
            | "match"
            | "namespace"
            | "new"
            | "null"
            | "or"
            | "print"
            | "private"
            | "protected"
            | "public"
            | "readonly"
            | "return"
            | "static"
            | "switch"
            | "throw"
            | "trait"
            | "true"
            | "try"
            | "unset"
            | "use"
            | "var"
            | "while"
            | "xor"
            | "yield"
    )
}

pub(super) fn is_builtin(word: &str) -> bool {
    matches!(
        word,
        "echo"
            | "print"
            | "die"
            | "exit"
            | "include"
            | "require"
            | "isset"
            | "unset"
            | "empty"
            | "array"
            | "list"
            | "eval"
            | "var_dump"
            | "print_r"
            | "strlen"
            | "count"
            | "array_push"
            | "array_pop"
            | "json_encode"
            | "json_decode"
            | "file_get_contents"
            | "file_put_contents"
            | "header"
            | "session_start"
            | "session_destroy"
            | "mysql_connect"
    )
}
