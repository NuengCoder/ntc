//! Css lexer traits and word tables.

use super::spec::LangSpec;

pub(super) const SPEC: LangSpec = LangSpec::new(b"")
    .with_block_comments()
    .with_css_at_rules()
    .at_rules(is_css_at_rule)
    .css_properties(is_css_property);

pub(super) fn is_css_at_rule(word: &str) -> bool {
    matches!(
        word,
        "@media"
            | "@import"
            | "@keyframes"
            | "@font-face"
            | "@page"
            | "@supports"
            | "@namespace"
            | "@document"
            | "@charset"
            | "@counter-style"
            | "@property"
            | "@layer"
            | "@scope"
            | "@starting-style"
            | "@container"
    )
}

