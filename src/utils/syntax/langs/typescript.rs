//! TypeScript lexer traits and word tables.

use super::spec::LangSpec;

pub(super) const SPEC: LangSpec = LangSpec::new(b"//")
    .with_block_comments()
    .with_regex_literals()
    .with_tag_syntax()
    .keywords(is_keyword)
    .builtins(is_builtin);

pub(super) fn is_keyword(word: &str) -> bool {
    matches!(
        word,
        "async"
            | "await"
            | "break"
            | "case"
            | "catch"
            | "class"
            | "const"
            | "continue"
            | "debugger"
            | "default"
            | "delete"
            | "do"
            | "else"
            | "enum"
            | "export"
            | "extends"
            | "false"
            | "finally"
            | "for"
            | "function"
            | "if"
            | "import"
            | "in"
            | "instanceof"
            | "let"
            | "new"
            | "null"
            | "of"
            | "return"
            | "super"
            | "switch"
            | "this"
            | "throw"
            | "true"
            | "try"
            | "typeof"
            | "var"
            | "void"
            | "while"
            | "with"
            | "yield"
            | "static"
            | "get"
            | "set"
            | "implements"
            | "interface"
            | "package"
            | "private"
            | "protected"
            | "public"
            | "readonly"
            | "type"
            | "namespace"
            | "declare"
            | "abstract"
            | "as"
            | "satisfies"
            | "infer"
            | "keyof"
            | "is"
            | "asserts"
            | "unknown"
            | "never"
            | "any"
    )
}

pub(super) fn is_builtin(word: &str) -> bool {
    matches!(
        word,
        "console"
            | "window"
            | "document"
            | "Math"
            | "JSON"
            | "Array"
            | "Object"
            | "String"
            | "Number"
            | "Boolean"
            | "Date"
            | "RegExp"
            | "Map"
            | "Set"
            | "WeakMap"
            | "WeakSet"
            | "Promise"
            | "Symbol"
            | "Error"
            | "undefined"
            | "NaN"
            | "Infinity"
            | "setTimeout"
            | "setInterval"
            | "clearTimeout"
            | "clearInterval"
            | "fetch"
            | "require"
            | "module"
            | "exports"
            | "process"
            | "Buffer"
            | "__dirname"
            | "__filename"
            | "global"
            | "globalThis"
            | "setImmediate"
            | "isNaN"
            | "parseInt"
            | "parseFloat"
            | "encodeURI"
            | "decodeURI"
            | "encodeURIComponent"
            | "decodeURIComponent"
            | "eval"
            | "BigInt"
            | "Reflect"
            | "Proxy"
            | "Intl"
            | "structuredClone"
            | "queueMicrotask"
    )
}
