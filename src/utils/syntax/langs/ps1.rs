            | "process"
            | "end"
            | "param"
            | "function"
            | "filter"
            | "class"
            | "enum"
            | "in"
            | "not"
            | "and"
            | "or"
            | "xor"
            | "is"
            | "as"
            | "true"
            | "false"
            | "null"
            | "New-Object"
            | "Write-Host"
            | "Write-Output"
            | "Write-Error"
            | "Get-ChildItem"
            | "Get-Item"
            | "Get-Content"
            | "Set-Content"
            | "Add-Content"
            | "Remove-Item"
            | "New-Item"
            | "Copy-Item"
            | "Move-Item"
            | "Rename-Item"
