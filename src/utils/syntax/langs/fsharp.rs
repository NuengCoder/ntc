            | "eprintfn"
            | "failwith"
            | "failwithf"
            | "invalidArg"
            | "invalidOp"
            | "raise"
            | "reraise"
            | "ignore"
            | "id"
            | "fst"
            | "snd"
            | "not"
            | "ref"
            | "incr"
            | "decr"
            | "box"
            | "unbox"
            | "typeof"
            | "typedefof"
