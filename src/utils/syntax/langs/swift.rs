//! Swift lexer traits and word tables.

use super::spec::LangSpec;

pub(super) const SPEC: LangSpec = LangSpec::new(b"//")
    .with_block_comments()
    .with_annotation_at()
    .with_upper_heuristic()
    .keywords(is_keyword)
    .type_names(is_type_name);

pub(super) fn is_keyword(word: &str) -> bool {
    matches!(
        word,
        "Any"
            | "as"
            | "associativity"
            | "break"
            | "case"
            | "catch"
            | "class"
            | "continue"
            | "convenience"
            | "default"
            | "defer"
            | "deinit"
            | "do"
            | "dynamic"
            | "else"
            | "enum"
            | "extension"
            | "fallthrough"
            | "false"
            | "fileprivate"
            | "final"
            | "for"
            | "func"
            | "get"
            | "guard"
            | "if"
            | "import"
            | "in"
            | "indirect"
            | "infix"
            | "init"
            | "inout"
            | "internal"
            | "is"
            | "lazy"
            | "let"
            | "mutating"
            | "nil"
            | "nonmutating"
            | "open"
            | "operator"
            | "optional"
            | "override"
            | "package"
            | "postfix"
            | "precedence"
            | "prefix"
            | "private"
            | "protocol"
            | "public"
            | "repeat"
            | "required"
            | "rethrows"
            | "return"
            | "self"
            | "Self"
            | "set"
            | "static"
            | "struct"
            | "subscript"
            | "super"
            | "switch"
            | "throw"
            | "throws"
            | "true"
            | "try"
            | "typealias"
            | "var"
            | "where"
            | "while"
            | "async"
            | "await"
            | "actor"
            | "some"
            | "any"
    )
}

pub(super) fn is_type_name(word: &str) -> bool {
    matches!(
        word,
        "Bool"
            | "Int"
            | "Int8"
            | "Int16"
            | "Int32"
            | "Int64"
            | "UInt"
            | "UInt8"
            | "UInt16"
            | "UInt32"
            | "UInt64"
            | "Float"
            | "Double"
            | "String"
            | "Character"
            | "Array"
            | "Dictionary"
            | "Set"
            | "Optional"
            | "Error"
            | "Result"
            | "Substring"
            | "Any"
            | "AnyObject"
    )
}
