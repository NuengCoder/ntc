use std::path::Path;

use anyhow::Result;

pub(super) fn generate_header_guard(stem: &str, ext: &str) -> String {
    stem.chars()
        .map(|c| {
            if c.is_alphanumeric() {
                c.to_ascii_uppercase()
            } else {
                '_'
            }
        })
        .collect::<String>()
        + "_"
        + &ext.to_ascii_uppercase()
        + "_"
}

fn generate_header_template(stem: &str, ext: &str) -> String {
    let guard = generate_header_guard(stem, ext);
    format!("#ifndef {guard}\n#define {guard}\n\n\n#endif // {guard}\n")
}

