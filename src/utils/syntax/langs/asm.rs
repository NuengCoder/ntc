//! Asm lexer traits and word tables.

use super::spec::LangSpec;

pub(super) const SPEC: LangSpec = LangSpec::new(b";")
    .keywords(is_keyword)
    .type_names(is_type_name)
    .builtins(is_builtin)
    .constants(is_constant);

pub(super) fn is_keyword(word: &str) -> bool {
    matches!(
        word,
        // GAS / AT&T and NASM common
        "section" | "segment" | "extern" | "public" | "bits" | "org"
            | "align" | "db" | "dw" | "dd" | "dq" | "dt" | "resb" | "resw"
            | "resd" | "resq" | "rest" | "times" | "use16" | "use32" | "use64"
            | "macro" | "endmacro" | "include" | "incbin" | "default" | "cpu"
            // Instruction-name keywords (only the ones that also read like
            // keywords; most instructions will render as builtins below)
            | "call" | "jmp" | "ret" | "retf" | "leave" | "enter" | "int" | "into"
            | "loop" | "loope" | "loopne" | "nop" | "hlt" | "push" | "pop"
            // Common directives
            | "if" | "else" | "endif" | "ifdef" | "ifndef" | "elif" | "define"
            | "undef" | "rept" | "endr" | "struc" | "endstruc" | "istruc" | "iend"
            | "at" | "global" | "weak" | "hidden" | "protected" | "set" | "equ"
    )
}

