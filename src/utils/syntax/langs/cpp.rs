//! Cpp lexer traits and word tables.

use super::spec::LangSpec;

pub(super) const SPEC: LangSpec = LangSpec::new(b"//")
    .with_block_comments()
    .with_char_literals()
    .keywords(is_keyword)
    .type_names(is_type_name);

pub(super) fn is_keyword(word: &str) -> bool {
    matches!(
        word,
        "alignas"
            | "alignof"
            | "auto"
            | "bool"
            | "break"
            | "case"
            | "catch"
            | "char"
            | "class"
            | "const"
            | "constexpr"
            | "consteval"
            | "constinit"
            | "concept"
            | "co_await"
            | "co_return"
            | "co_yield"
            | "continue"
            | "decltype"
            | "default"
            | "delete"
            | "do"
            | "double"
            | "else"
            | "enum"
            | "explicit"
            | "export"
            | "extern"
            | "false"
            | "float"
            | "for"
            | "friend"
            | "goto"
            | "if"
            | "inline"
            | "int"
            | "long"
            | "mutable"
            | "namespace"
            | "new"
            | "noexcept"
            | "nullptr"
            | "operator"
            | "override"
            | "private"
            | "protected"
            | "public"
            | "register"
            | "requires"
            | "return"
            | "short"
            | "signed"
            | "sizeof"
            | "static"
            | "static_assert"
            | "static_cast"
            | "struct"
            | "switch"
            | "template"
            | "this"
            | "thread_local"
            | "throw"
            | "true"
            | "try"
            | "typedef"
            | "typeid"
            | "typename"
            | "union"
            | "unsigned"
            | "using"
            | "virtual"
            | "void"
            | "volatile"
            | "while"
    )
}

pub(super) fn is_type_name(word: &str) -> bool {
    matches!(
        word,
        "size_t"
            | "nullptr_t"
            | "string"
            | "vector"
            | "map"
            | "set"
            | "list"
            | "deque"
            | "array"
            | "unordered_map"
            | "unordered_set"
            | "shared_ptr"
            | "unique_ptr"
            | "weak_ptr"
            | "function"
            | "pair"
            | "tuple"
            | "optional"
            | "any"
            | "variant"
            | "string_view"
            | "span"
            | "atomic"
            | "thread"
            | "mutex"
            | "filesystem"
    )
}
