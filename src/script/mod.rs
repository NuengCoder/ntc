/// Extension used for ntc automation scripts.
pub(crate) const SCRIPT_EXT: &str = "ntc";

/// Show `scr` usage.
pub(crate) fn print_usage() {
    println!("{}", t!("scr.help_title").cyan().bold());
    println!();
    println!("{}", t!("scr.help_usage"));
    println!("{}", t!("scr.help_run"));
    println!("{}", t!("scr.help_continue"));
    println!("{}", t!("scr.help_init"));
    println!("{}", t!("scr.help_ls"));
    println!("{}", t!("scr.help_help"));
    println!();
    println!("{}", t!("scr.desc_set").yellow());
    println!("{}", t!("scr.desc_force").yellow());
    println!("{}", t!("scr.desc_args").yellow());
    println!("{}", t!("scr.desc_interp").yellow());
}

/// Default template generated by `scr init`.
pub(crate) fn script_template() -> &'static str {
    r#"# script.ntc — ntc automation script
# Run with: scr script.ntc [args...]
# Each line is a command: ntc builtin, run alias, or system command.

# Define variables (values are interpolated immediately)
set name = "world"
set dir = "src"

# ntc command (supports $var / ${var} / ${var:-default})
cd $dir
say "Hello $name"

# system command (fallback when not an ntc builtin)
echo done

# force a system command (bypasses ntc builtins)
@ echo forced system command

# positional script args: $1 $2 ... $@
say "First arg: $1"
"#
}

/// List `*.ntc` scripts in a directory (sorted).
pub(crate) fn list_scripts(cwd: &Path) -> Result<Vec<std::path::PathBuf>> {
    let mut scripts = Vec::new();
    if let Ok(entries) = std::fs::read_dir(cwd) {
        for entry in entries.flatten() {
            let path = entry.path();
            if path.is_file() && path.extension().is_some_and(|e| e == SCRIPT_EXT) {
                scripts.push(path);
            }
        }
    }
    scripts.sort();
    Ok(scripts)
}
