//! Vim lexer traits and word tables.

use super::spec::LangSpec;

pub(super) const SPEC: LangSpec = LangSpec::new(b"")
    .keywords(is_keyword)
    .builtins(is_builtin)
    // Vim has no type names: an explicit empty table keeps capitalised
    // identifiers from reading as types (the legacy fallback for languages
    // without one).
    .type_names(no_type);

fn no_type(_: &str) -> bool {
    false
}

