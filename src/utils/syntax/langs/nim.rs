//! Nim lexer traits and word tables.

use super::spec::LangSpec;

pub(super) const SPEC: LangSpec = LangSpec::new(b"//").keywords(is_keyword);

pub(super) fn is_keyword(word: &str) -> bool {
    matches!(
        word,
        "addr"
            | "and"
            | "as"
            | "asm"
            | "atomic"
            | "bind"
            | "block"
            | "break"
            | "case"
            | "cast"
            | "const"
            | "continue"
            | "converter"
            | "defer"
            | "discard"
            | "distinct"
            | "div"
            | "do"
            | "elif"
            | "else"
            | "end"
            | "enum"
            | "except"
            | "export"
            | "finally"
            | "for"
            | "from"
            | "func"
            | "generic"
            | "if"
            | "import"
            | "in"
            | "include"
            | "interface"
            | "is"
            | "isnot"
            | "iterator"
            | "let"
            | "macro"
            | "method"
            | "mixin"
            | "mod"
            | "nil"
            | "not"
            | "notin"
            | "object"
            | "of"
            | "or"
            | "out"
            | "proc"
            | "ptr"
            | "raise"
            | "ref"
            | "return"
            | "shl"
            | "shr"
            | "static"
            | "template"
            | "try"
            | "tuple"
            | "type"
            | "using"
            | "var"
            | "when"
            | "while"
            | "with"
            | "without"
            | "xor"
            | "yield"
    )
}
