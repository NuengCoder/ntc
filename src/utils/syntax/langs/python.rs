//! Python lexer traits and word tables.

use super::spec::LangSpec;

pub(super) const SPEC: LangSpec = LangSpec::new(b"#")
    .with_annotation_at()
    .keywords(is_keyword)
    .builtins(is_builtin);

pub(super) fn is_keyword(word: &str) -> bool {
    matches!(
        word,
        "False"
            | "None"
            | "True"
            | "and"
            | "as"
            | "assert"
            | "async"
            | "await"
            | "break"
            | "class"
            | "continue"
            | "def"
            | "del"
            | "elif"
            | "else"
            | "except"
            | "finally"
            | "for"
            | "from"
            | "global"
            | "if"
            | "import"
            | "in"
            | "is"
            | "lambda"
            | "nonlocal"
            | "not"
            | "or"
            | "pass"
            | "raise"
            | "return"
            | "try"
            | "while"
            | "with"
            | "yield"
            | "match"
            | "case"
    )
}

pub(super) fn is_builtin(word: &str) -> bool {
    matches!(
        word,
        "print"
            | "len"
            | "range"
            | "int"
            | "str"
            | "float"
            | "list"
            | "dict"
            | "set"
            | "tuple"
            | "bool"
            | "type"
            | "super"
            | "isinstance"
            | "hasattr"
            | "getattr"
            | "setattr"
            | "open"
            | "input"
            | "map"
            | "filter"
            | "zip"
            | "enumerate"
            | "reversed"
            | "sorted"
            | "any"
            | "all"
            | "sum"
            | "min"
            | "max"
            | "abs"
            | "round"
            | "ord"
            | "chr"
            | "repr"
            | "format"
            | "iter"
            | "next"
            | "property"
            | "staticmethod"
            | "classmethod"
            | "object"
            | "Exception"
            | "BaseException"
            | "ValueError"
            | "TypeError"
            | "KeyError"
            | "IndexError"
            | "AttributeError"
            | "IOError"
            | "ImportError"
            | "StopIteration"
            | "RuntimeError"
            | "NotImplementedError"
            | "self"
            | "cls"
    )
}
