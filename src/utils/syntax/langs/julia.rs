//! Julia lexer traits and word tables.

use super::spec::LangSpec;

pub(super) const SPEC: LangSpec = LangSpec::new(b"#")
    .with_block_comments()
    .with_char_literals()
    .with_upper_heuristic()
    .keywords(is_keyword)
    .type_names(is_type_name)
    .builtins(is_builtin);

pub(super) fn is_keyword(word: &str) -> bool {
    matches!(
        word,
        "abstract"
            | "baremodule"
            | "begin"
            | "break"
            | "catch"
            | "ccall"
            | "const"
            | "continue"
            | "do"
            | "else"
            | "elseif"
            | "end"
            | "export"
            | "false"
            | "finally"
            | "for"
            | "function"
            | "global"
            | "if"
            | "import"
            | "in"
            | "let"
            | "local"
            | "macro"
            | "module"
            | "mutable"
            | "primitive"
            | "quote"
            | "return"
            | "struct"
            | "true"
            | "try"
            | "using"
            | "where"
            | "while"
    )
}

